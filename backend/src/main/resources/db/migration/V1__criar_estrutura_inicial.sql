
CREATE TABLE public.usuario (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nome VARCHAR(120) NOT NULL,
    email VARCHAR(254) NOT NULL,
    senha_hash VARCHAR(255) NOT NULL,
    criado_em TIMESTAMP(6) NOT NULL DEFAULT CURRENT_TIMESTAMP,

    CONSTRAINT ck_usuario_nome
        CHECK (LENGTH(BTRIM(nome)) > 0),

    CONSTRAINT ck_usuario_email
        CHECK (
            LENGTH(BTRIM(email)) > 3
            AND email = LOWER(BTRIM(email))
            AND POSITION('@' IN email) > 1
        ),

    CONSTRAINT ck_usuario_senha_hash
        CHECK (LENGTH(BTRIM(senha_hash)) > 0),

    CONSTRAINT uq_usuario_email UNIQUE (email)
);

CREATE TABLE public.tarefa (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    titulo VARCHAR(120) NOT NULL,
    descricao VARCHAR(2000),
    status VARCHAR(20) NOT NULL,
    prioridade VARCHAR(10) NOT NULL,
    data_criacao TIMESTAMP(6) NOT NULL,
    usuario_id BIGINT NOT NULL,

    CONSTRAINT ck_tarefa_titulo
        CHECK (LENGTH(BTRIM(titulo)) > 0),

    CONSTRAINT ck_tarefa_status
        CHECK (
            status IN (
                'PENDENTE',
                'EM_ANDAMENTO',
                'CONCLUIDA'
            )
        ),

    CONSTRAINT ck_tarefa_prioridade
        CHECK (
            prioridade IN (
                'BAIXA',
                'MEDIA',
                'ALTA'
            )
        ),

    CONSTRAINT fk_tarefa_usuario
        FOREIGN KEY (usuario_id)
        REFERENCES public.usuario(id)
        ON DELETE RESTRICT
);

CREATE INDEX idx_tarefa_usuario_id
ON public.tarefa (usuario_id, id);
